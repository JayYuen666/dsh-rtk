// test/build-host.test.ts —— host 产物的三道门：与源码同步（指纹）、跨包依赖外部化、无 .ts 残留。
//
// 为什么值得一条测试（三个坏方向都不报错、只在线上发作）：发布形态下 host.js 躺在
// node_modules 里被 dsh 载入——
//   1) 内联：`@jayyuen66/dsh-plugin-shared/lib/locale` 这类**子路径**说明符一旦被打进产物，
//      shared 的模块级状态就在每个插件里各复制一份；rolldown 的 external 字符串项是精确匹配，
//      只列包名会漏掉子路径，故 build-host.mjs 按「包名段」判定（该坑已在脚本注释登记）。
//      宿主包同理：它们内联进来就是第二份实例，而且宿主自己对「字面版本 peer」做确切版本校验，
//      内联躲开了校验但躲不开语义分叉。
//   2) 残留：产物里只要还剩 `./lib/xxx.ts`，Node 载入即抛 ERR_UNSUPPORTED_NODE_MODULES_
//      TYPE_STRIPPING。
//   3) 过期：改 host.ts / lib/*.ts 之后忘跑 node build-host.mjs，宿主载入的仍是旧逻辑，
//      而单测读的是源码，一路绿。
import { describe, it } from "vitest";
import assert from "node:assert/strict";

import { buildHost } from "../build-host.mjs";
import { hostFreshnessEvidence } from "./host-freshness.ts";

/** 值导入的宿主包：每一个都必须以裸说明符留在产物里（外部化），不得内联。 */
const HOST_SPECIFIERS = [
  "@deepseek-ai/dsh-llm",
  "@deepseek-ai/dsh-output-retention",
  "@deepseek-ai/dsh-storage-domain",
  "@deepseek-ai/dsh-typert-protocol",
  "@deepseek-ai/dsh-util-values",
  "@deepseek-ai/schemastery",
] as const;

/** shared 的子路径：逐个列名才拦得住「某个新接的子路径被内联」这类回退。 */
const SHARED_SUBPATHS = ["lib/errors", "lib/locale", "lib/record"] as const;

describe("buildHost()", () => {
  it("host.js 与最新构建逐字节一致（改 host.ts / lib/*.ts 后必须 node build-host.mjs）", async () => {
    const { pkgName, pkgDir, onDisk, built } = await hostFreshnessEvidence(import.meta.url);
    assert.equal(
      onDisk,
      built,
      `[${pkgName}] host.js 已过期：host.ts（或其依赖）变更后未重建。请运行：cd ${pkgDir} && node build-host.mjs`,
    );
  });

  it("产物 host.js：运行期跨包依赖保持 external（未内联）", async () => {
    const out = await buildHost();
    assert.ok(
      out.startsWith("// GENERATED by build-host.mjs"),
      "产物须带生成标记（勿手改 host.js）",
    );
    // 宿主包一律走 peer 那一边，不进 dependencies——理由见 publish-manifest 的门禁。
    for (const specifier of HOST_SPECIFIERS) {
      assert.ok(
        out.includes(`from "${specifier}"`),
        `${specifier} 必须以裸说明符形式留在产物里（成 peer 才外部化，见 build-host.mjs）`,
      );
    }
    // 反向锁：不得退回公共 schemastery（0.1.7 起用的是宿主 fork，`.volatile()` 只在它里面）。
    assert.ok(
      !/from\s+["']schemastery["']/u.test(out),
      "host.js 不得再值导入公共 schemastery（.volatile() 解析只在宿主 fork 里）",
    );
    // shared 子路径：**逐个**列名——只查前缀会被一条满足，看不见新接进来的子路径。
    for (const subpath of SHARED_SUBPATHS) {
      assert.ok(
        out.includes(`from "@jayyuen66/dsh-plugin-shared/${subpath}"`),
        `shared/${subpath} 必须外部化（裸说明符形式留在产物里）`,
      );
    }
    // 自有 lib 的记号必须「在产物内」（内联成功）而不是留成相对说明符。
    assert.ok(out.includes("rtk: stats domain"), "lib/stats-store.ts 的域标签须已并入单文件产物");
    assert.ok(!/from\s*["']\.\/lib\//u.test(out), "自有 lib 不得留成相对说明符");
  });

  it("产物 host.js：不残留 ./x.ts 形态的相对说明符", async () => {
    const out = await buildHost();
    assert.ok(!/["']\.\/[^"']*\.ts["']/u.test(out), "不得有 ./x.ts 说明符残留");
  });

  it("产物 host.js：没有本机绝对路径与 pnpm store 布局的注释", async () => {
    // rolldown 会把内联模块的**来源路径**写进产物注释。一旦某个宿主包漏出 peer 名单被整包内联，
    // 这里就会出现 `../node_modules/.pnpm/<pkg>@<ver>/...` —— 既暴露本机布局，也让产物不可复现。
    const out = await buildHost();
    assert.doesNotMatch(out, /\.pnpm[\\/]/u, "产物里有 pnpm store 布局的路径注释");
    assert.doesNotMatch(out, /\/(?:Users|home)\/[\w.-]+/u, "产物里有本机绝对路径");
  });
});
