#!/usr/bin/env node
// @ts-check
/// <reference types="node" />
// 构建客户端产物：rolldown 把 src/client-entry.ts 及其依赖打包为 CJS（react / zod 精确外置），
// 再包进 window.__ModuleLoader__.load({ id, factory }) UMD 外壳。id 取 package.json 的 name，
// 与 dsh.client 模块表键一致。
//
// **分两件产物**：入口 `client.js` 与包内 chunk `client.insights-echarts.js`。chunk 里是
// ECharts 与画图那段代码——用户没打开图表就一个字节都不下载（宿主按
// `require.async("./client.<name>.js")` 现拉）。入口里那句 `require.async` 必须是**字面量**：
// 构建层靠它核对「声明了 chunk 就必须有人引用」，宿主也按同一根串算 chunkId。
//
// 编排（外置判据、store 路径折叠、外壳拼装、逐份产物的六道门）统一实现在
// @jayyuen66/dsh-plugin-shared/lib/build-client；本文件只声明入口、chunk 清单、生成头与
// 本仓自有的包名同源校验（槽位 key 与 $mount 的 package 位各持一份字面量，构建期对不齐当场红）。
// 运行：node build-client.mjs（或 npm run build:client）。buildClient() 与 buildClientFiles()
// 供测试导入。
import path from "node:path";
import { rolldown } from "rolldown";
import {
  buildClientArtifacts,
  buildClientBundle,
  REACT_RUNTIME_MODULES,
} from "@jayyuen66/dsh-plugin-shared/lib/build-client";
import { invokedDirectly, writeArtifact } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

// 测试按「脚本自己导出它用的工具」这一规则从本模块导入 singleEntryChunk。
export { singleEntryChunk } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

const root = import.meta.dirname;

/**
 * 包名同源的一次核对，两次调用共用这一份判据。
 *
 * 比的是**带引号的字面量原文**，不 `JSON.parse`：包名不需要转义，而 JSON.parse 会把合法 JS、
 * 非法 JSON 的转义（`\/`、`\x41`、`\u{…}`、行继续符）抛成 SyntaxError，先坏掉的是判据本身，
 * 报出来的不再是「两者不同源」这句写好的话。正则只认双引号声明：源码改用单引号或反引号时走
 * 「找不到声明」那一条红，不会静默通过。
 * 捕获组命名（lint 要求）但按位置取值：`groups` 是索引签名，括号访问与点号访问两条规则互相
 * 打架，位置索引对两边都成立。
 * @param {{source: string, pattern: RegExp, want: string, where: string, miss: string, harm: string}} check
 * 一份待核对的声明：`source` 是承载它的那份文本，`pattern` 捕获带引号的字面量原文，
 * `want` 是 `JSON.stringify(package.json.name)`，`where`/`miss`/`harm` 供两条报错点名对象与后果。
 */
function assertSameName({ source, pattern, want, where, miss, harm }) {
  const literal = pattern.exec(source)?.[1];
  if (literal === undefined) {
    throw new Error(miss);
  }
  if (literal !== want) {
    throw new Error(
      `build-client：${where} 是 ${literal}，package.json 的 name 是 ${want}——两者不同源，${harm}`,
    );
  }
}

// 外置清单 = 既有 react 家族 + zod（宿主 `PLATFORM_MODULES` 里本卡值导入的第三方运行时）。
// 不复用 shared 的默认清单：它随 shared 版本变化，而消费者 CI 装的是 registry 上那一份；
// 这里显式列出本仓需要外置的说明符。`buildClientArtifacts` 与 `chunks` 由 shared 0.2.11
// 起提供，因此本仓声明的 shared 下限不能低于 ^0.2.11；低于它时构建期会找不到这个导出。
// zod 内联会打进每份 client.js，并让同一页面出现两份 zod 身份。
//
// shared 的 `./client` 由 cordis.patch.yml 插入的固定 id `dsh-plugin-shared` 供应行装载成
// 模块表条目；该供应行必须保持开启。package.json 的 dsh.client.external 同步声明这一条，
// 供宿主按依赖边排序。
// 历史教训：只作为传递依赖安装、宿主没把 shared 排进启动图时，页面启动会落进
// "missed the module table"（dsh-ocr-review 仓 issue #2，宿主 0.2.2-rc.1 dsh desktop）。
// 本仓现在显式启用供应行，并接受「shared 必须作为 client row 被宿主装载」这一前提。
const CLIENT_EXTERNALS = [
  ...REACT_RUNTIME_MODULES,
  "zod",
  // 宿主的确认弹窗原子（Modal / RiskConfirmation）：平台模块，冻结模块表里已有，
  // 内联会把整份 primitives 打进本卡并让同一页面出现第二份 identity。
  "@deepseek-ai/dsh-client-ui-primitives",
  "@jayyuen66/dsh-plugin-shared/client",
];

/** 图表 chunk 的产物名。必须匹配宿主的 `client.<name>.js`，并且与入口里那根字面量串逐字相同。 */
const CHUNK_FILE = "client.insights-echarts.js";

/** 图表 chunk 的源文件（相对包根）。它只在 `require.async` 的时刻被下载。 */
const CHUNK_SOURCE = path.join("src", "insights-echarts.ts");

// 生成头由**所有**产物共用（入口与 chunk 都写它），所以它只点目录、不点具体文件：
// chunk 的源是 `src/insights-echarts.ts`，头部若写死 `src/client-entry.ts`，看产物的人会去改
// 一个与这份产物无关的文件。
const HEADER =
  "// GENERATED by buildClient() in build-client.mjs — edit the sources under src/, then run `node build-client.mjs`.";

/**
 * 包名同源核对。两份产物各调一次（入口与 chunk 的外壳 id 都来自同一个包名），
 * 所以判据只有一份。
 * @param {{pkgName: string, readSource: (file: string) => Promise<string>}} sources
 * `pkgName` 取自 `package.json.name`，`readSource` 读包内相对路径的源码文本。
 */
async function verifyNameOf({ pkgName, readSource }) {
  // 槽位 key 写死在 src 的 BUNDLE_PKG，外壳的 id 取自 package.json.name，两者不同源。
  // 宿主按包名逐字匹配模块表键，对不上就是整张卡静默不渲染，而改名在别的环节没有症状。
  // 所以判据必须读声明值本身：产物里包名一共出现多次（外壳的 id、BUNDLE_PKG 的声明与引用），
  // 拿 includes 去判会被其中任意一处满足，而这个不变量要的正是「这几处同源」。
  const want = JSON.stringify(pkgName);
  // 压缩会 mangle 局部标识符，BUNDLE_PKG 的声明在产物里可能已经消失（被内联成字面量）。
  // 判据改读**源码声明**，不依赖产物的可读性。
  assertSameName({
    source: await readSource(path.join("src", "client-entry.ts")),
    pattern: /(?:const|let|var)\s+BUNDLE_PKG\s*=\s*(?<literal>"(?:[^"\\]|\\.)*")/u,
    want,
    where: "src 的 BUNDLE_PKG",
    miss: "build-client：src/client-entry.ts 里找不到 BUNDLE_PKG 的声明，槽位 key 无从核对。",
    harm: "槽位 key 与模块表键会对不上。",
  });
  // $mount 的 package 位（src/stats-reader.ts 的 PACKAGE_NAME）与槽位 key 是同一个包名，
  // 但各自持有一份字面量：对不上时既不报错也不生效，只表现为运行期「命名空间未提供」。
  assertSameName({
    source: await readSource(path.join("src", "stats-reader.ts")),
    pattern: /(?:const|let|var)\s+PACKAGE_NAME\s*=\s*(?<literal>"(?:[^"\\]|\\.)*")/u,
    want,
    where: "src/stats-reader.ts 的 PACKAGE_NAME",
    miss: "build-client：src/stats-reader.ts 里找不到 PACKAGE_NAME 的声明，$mount 的 package 位无从核对。",
    harm: "$mount 会静默挂不上。",
  });
}

/** 生成 client.js 的完整文本（含 ModuleLoader 外壳）。测试与新鲜度门都用它。 */
export async function buildClient() {
  return buildClientBundle({
    root,
    rolldown,
    externals: CLIENT_EXTERNALS,
    minify: true,
    header: HEADER,
    verifyName: verifyNameOf,
  });
}

/**
 * 生成全部客户端产物：入口在前，图表 chunk 在其后。
 *
 * 每次调用都重新构建（测试要与磁盘产物逐字节比），所以这里不发缓存。
 */
export async function buildClientFiles() {
  return buildClientArtifacts({
    root,
    rolldown,
    externals: CLIENT_EXTERNALS,
    minify: true,
    header: HEADER,
    verifyName: verifyNameOf,
    chunks: [{ source: CHUNK_SOURCE, fileName: CHUNK_FILE }],
  });
}

async function main() {
  // 一件一件写：`writeArtifact` 自己用「临时名 + rename」做原子替换，并发本来也安全；排成
  // 一串只是为了日志按声明的顺序出（入口在前、chunk 在后），排查时不必在两行之间对号。
  // 用 `Promise.all` 而不是 `for ... await`：后者会被 `no-await-in-loop` 判红，而这条规则
  // 在本仓是硬性的——与其关规则，不如让它们同时发、同时收。
  const artifacts = await buildClientFiles();
  const written = await Promise.all(
    artifacts.map(async (artifact) => {
      await writeArtifact(path.join(root, artifact.fileName), artifact.text);
      console.info(
        artifact.fileName,
        "written:",
        Buffer.byteLength(artifact.text, "utf8"),
        "bytes",
      );
      return artifact.fileName;
    }),
  );
  return written;
}

if (invokedDirectly(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    // 用 exitCode 而不是 process.exit：后者会在 stdout/stderr 管道被占满时截断错误输出。
    console.error(error);
    process.exitCode = 1;
  }
}
